//300pts * 33% = 100pts
#include <bits/stdc++.h>
using namespace std;
int n, a[5005];
int chk(int l, int r)
{
	int sum = 0;
	for(int i = 0; i <= (r - l) / 2; i++)
		sum += abs(a[l + i] - a[r - i]);
	return sum;
}
int main()
{
	cin >> n;
	for(int i = 1; i <= n; i++)
		cin >> a[i];
	if(n <= 300)
	{
		for(int len = 1; len <= n; len++)
		{
			int k = 1145141919;
			for(int i = 1; i + len - 1 <= n; i++)
				k = min(k, chk(i, i + len - 1));
			cout << k << " ";
		}
	}
	else
	{
		for(int i = 1; i <= n; i++)
			cout << "0 ";
	}
	return 0;
}
