#include<bits/stdc++.h>
using namespace std;
int n;
int a[3][200005];
int c[3][200005][3];
int main()
{
	cin >> n;
	for(int i = 1; i <= n; i++)
	{
		cin >> a[1][i];
		if(a[1][i]==0)continue;
		c[1][i][0]=(c[1][i][0]+1)%2;
		c[1][i][1]=(c[1][i][1]+1)%2;
		c[1][i][2]=(c[1][i][2]+1)%2;
		if(i%2==1)c[2][i][0]=(c[2][i][0]+1)%2;
		if(i>1)c[1][i-1][2]=(c[1][i-1][2]+1)%2;
		if(i<n)c[1][i+1][1]=(c[1][i+1][1]+1)%2;
	}
	for(int i = 1; i <= n; i++)
	{
		cin >> a[2][i];
		if(a[2][i]==0)continue;
		c[2][i][0]=(c[2][i][0]+1)%2;
		c[2][i][1]=(c[2][i][1]+1)%2;
		c[2][i][2]=(c[2][i][2]+1)%2;
		if(i%2==1)c[1][i][0]=(c[1][i][0]+1)%2;
		if(i>1)c[2][i-1][2]=(c[2][i-1][2]+1)%2;
		if(i<n)c[2][i+1][1]=(c[2][i+1][1]+1)%2;
	}
	int ans=0;
	for(int i = 1; i <= n; i++)
	{
		if(a[1][i]==1)ans+=c[1][i][0]+c[1][i][1]+c[1][i][2];
		if(a[2][i]==1)ans+=c[2][i][0]+c[2][i][1]+c[2][i][2];
	}
	cout << ans;
}
